class TestBuildConfigHypridle(unittest.TestCase):
    """Tests for hypridle config generation."""

    def setUp(self):
        self.patcher = patch('build_config.atomic_write')
        self.mock_atomic_write = self.patcher.start()

    def tearDown(self):
        self.patcher.stop()

    def test_hypridle_basic(self):
        """Test basic hypridle config generation."""
        mock_data = {
            "idle": {
                "lock_timeout": 300,
                "screen_off_timeout": 330,
                "suspend_timeout": 1800
            }
        }

        build_config.generate_hypridle_conf(mock_data)

        written = ""
        for call in self.mock_atomic_write.call_args_list:
            if call.args[0] == build_config.HYPRIDLE_CONF:
                written = call.args[1]
                break

        self.assertIn("timeout = 300", written)
        self.assertIn("timeout = 330", written)
        self.assertIn("timeout = 1800", written)
        self.assertIn("lock_cmd = pidof hyprlock || hyprlock", written)

    def test_hypridle_dpms_syntax(self):
        """Test dpms commands use hl.dsp.dpms syntax."""
        mock_data = {"idle": {"lock_timeout": 300, "screen_off_timeout": 330, "suspend_timeout": 1800}}

        build_config.generate_hypridle_conf(mock_data)

        written = ""
        for call in self.mock_atomic_write.call_args_list:
            if call.args[0] == build_config.HYPRIDLE_CONF:
                written = call.args[1]
                break

        self.assertIn("hl.dsp.dpms(\"on\")", written)
        self.assertIn("hl.dsp.dpms(\"off\")", written)
        # Old syntax should NOT appear
        self.assertNotIn("hyprctl dispatch dpms", written)

    def test_hypridle_no_idle_section(self):
        """Test that hypridle generation is skipped without idle section."""
        mock_data = {}

        with patch("builtins.open") as mocked_file:
            build_config.generate_hypridle_conf(mock_data)
            mocked_file.assert_not_called()


