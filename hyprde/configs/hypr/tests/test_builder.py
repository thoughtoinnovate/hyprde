class TestLuaGeneratorBasic(unittest.TestCase):
    """Tests for the Lua generator core."""

    def test_header_generated(self):
        """Test that output starts with the generated header."""
        lua = lua_generator.generate_user_lua({})
        self.assertIn("Generated by hyprde", lua)
        self.assertIn("hyprde.toml", lua)

    def test_programs_as_local_vars(self):
        """Test programs section produces local variables."""
        data = {"programs": {"terminal": "kitty", "fileManager": "thunar"}}
        lua = lua_generator.generate_user_lua(data)
        self.assertIn('local terminal = "kitty"', lua)
        self.assertIn('local fileManager = "thunar"', lua)

    def test_main_mod_from_binds(self):
        """Test mainMod is written from binds section."""
        data = {"binds": {"mainMod": "ALT", "normal": {"list": []}}}
        lua = lua_generator.generate_user_lua(data)
        self.assertIn('local mainMod = "ALT"', lua)

    def test_monitors_hl_monitor_call(self):
        """Test monitors produce hl.monitor() calls."""
        data = {
            "monitors": {
                "rules": ["DP-1, 1920x1080@60, 0x0, 1", ", highres, auto, 1"]
            }
        }
        lua = lua_generator.generate_user_lua(data)
        self.assertIn('hl.monitor({ output = "DP-1", mode = "1920x1080@60", position = "0x0", scale = "1" })', lua)
        self.assertIn('hl.monitor({ output = "", mode = "highres", position = "auto", scale = "1" })', lua)

    def test_env_section(self):
        """Test env section generates hl.config({ env = ... })."""
        data = {"env": {"vars": ["XCURSOR_SIZE,24", "HYPRCURSOR_SIZE,24"]}}
        lua = lua_generator.generate_user_lua(data)
        self.assertIn('hl.config({\n    env = {', lua)
        self.assertIn('"XCURSOR_SIZE,24"', lua)
        self.assertIn('"HYPRCURSOR_SIZE,24"', lua)

    def test_empty_data_does_not_crash(self):
        """Test that empty TOML data produces valid output."""
        lua = lua_generator.generate_user_lua({})
        self.assertIsInstance(lua, str)
        self.assertGreater(len(lua), 0)


